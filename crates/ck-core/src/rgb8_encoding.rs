#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn original_cpu_rgb24_known_answers_and_finite_domain() {
        // Independent unchanged-source oracle anchors, including both sides
        // of the sRGB piecewise boundary (bytes10/11).
        for (byte, bits) in [
            (0, 0x00000000),
            (1, 0x3b95dc39),
            (10, 0x3d3724b3),
            (11, 0x3d48fd7f),
            (64, 0x3e9dd5fd),
            (128, 0x3ef639ae),
            (255, 0x3f2a6c54),
        ] {
            assert_eq!(encode(byte).to_bits(), bits);
        }
        assert!((0..=255).all(|byte| encode(byte).is_finite()));
        assert!((0..255).all(|byte| encode(byte) < encode(byte + 1)));
    }
}
