//! Exact original CPU preprocessing for default-adjustment RGB24 input.
//!
//! Captured from unchanged `color_utils.srgb_to_linear` (Torch CPU) followed by
//! `linear_to_asinh` (NumPy CPU), after float32(byte)/float32(255). The model
//! executes on CUDA, but original video preprocessing executes on CPU.
//! This finite-domain table avoids platform transcendental rounding differences.
//! It must not replace the general signed HDR/float color transformations.
//!
//! Oracle: Torch 2.9.1+cu128, NumPy 1.26.4, brightness=contrast=1, pivot=0.18.
//! Original color_utils.py SHA256:
//! aa665cf9a82898f6725366a1b3879f0b0cf7a017e84b01522a447a9e08110641
//! Original video_io.py SHA256:
//! 28f4a789c1d8855d3bbe7d6ed1419d7aa16bbe03b134815f2f3adbae8caa6b04
//! Reproduce with tools/model_export/capture_rgb8_preprocess_lut.py.

